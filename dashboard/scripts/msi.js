// The Windows installer: dist/win-unpacked turned into one .msi with the WiX Toolset 3.x
// (candle and light), the same way Ultimate Cache Manager builds its installer. Nothing is
// downloaded; WiX is found through %WIX% or on PATH.
//
// The installer is per-user: no admin prompt, and it installs into %LOCALAPPDATA%. Besides the
// app it adds Start menu and desktop shortcuts, and a Startup shortcut that starts the watcher,
// hidden, at login. The watcher keeps its data in %LOCALAPPDATA%\Local Device Monitor\Data,
// which the installer never touches, so upgrading or uninstalling keeps the history.
//
// Files are grouped one component per folder, each keyed on an HKCU value: the Windows
// Installer's rule for anything installed into a user's profile.

const { execFileSync } = require('node:child_process');
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

// Identifies the product across versions. Must never change, or every existing install ends
// up beside the new one instead of being replaced.
const UPGRADE_CODE = 'F1403E97-5282-4B15-B6B8-23560E5A4EB5';
const NAME = 'Local Device Monitor';
const MANUFACTURER = 'LadderGoat';
const EXE = NAME + '.exe';
const REG = `Software\\${MANUFACTURER}\\${NAME}`;

function wixTool(name) {
  const dirs = [];
  if (process.env.WIX) dirs.push(path.join(process.env.WIX, 'bin'));
  dirs.push(...(process.env.PATH || '').split(path.delimiter).filter(Boolean));
  for (const dir of dirs) {
    const exe = path.join(dir, name + '.exe');
    if (fs.existsSync(exe)) return exe;
  }
  throw new Error(`${name}.exe was not found - install the WiX Toolset 3.x and put its bin folder on PATH`);
}

const hash = (text) => crypto.createHash('md5').update(text).digest('hex').toUpperCase();
const id = (prefix, rel) => prefix + hash(rel);
// Stable per folder, so the same layout builds the same package.
const guid = (rel) => {
  const h = hash(UPGRADE_CODE + '|' + rel);
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`;
};
const xml = (text) => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** The folder's components, nested as WiX wants them, and every component id. */
function harvest(source) {
  const components = [];
  let exeId = null;
  const walk = (dir, rel, indent) => {
    const entries = fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name));
    const comp = id('c', rel || '.');
    components.push(comp);
    const lines = [
      `${indent}<Component Id="${comp}" Guid="${guid(rel || '.')}">`,
      `${indent}  <RegistryValue Root="HKCU" Key="${xml(REG)}\\Files" Name="${comp}" Type="integer" Value="1" KeyPath="yes" />`,
      `${indent}  <RemoveFolder Id="${id('r', rel || '.')}" On="uninstall" />`,
    ];
    for (const e of entries.filter((e) => e.isFile())) {
      const fileRel = rel ? `${rel}/${e.name}` : e.name;
      const fileId = id('f', fileRel);
      if (fileRel === EXE) exeId = fileId;
      lines.push(`${indent}  <File Id="${fileId}" Name="${xml(e.name)}" Source="${xml(path.join(dir, e.name))}" />`);
    }
    lines.push(`${indent}</Component>`);
    for (const e of entries.filter((e) => e.isDirectory())) {
      const subRel = rel ? `${rel}/${e.name}` : e.name;
      lines.push(`${indent}<Directory Id="${id('d', subRel)}" Name="${xml(e.name)}">`);
      lines.push(...walk(path.join(dir, e.name), subRel, indent + '  '));
      lines.push(`${indent}</Directory>`);
    }
    return lines;
  };
  const tree = walk(source, '', '          ');
  if (!exeId) throw new Error(`${EXE} is not in ${source} - was the app built with productName "${NAME}"?`);
  return { tree, components, exeId };
}

function product({ version, icon, tree, components, exeId }) {
  const refs = [...components, 'RememberDir', 'StartMenuShortcut', 'DesktopShortcut', 'LoginShortcut']
    .map((c) => `      <ComponentRef Id="${c}" />`);
  // The same hidden start the dashboard uses: conhost without a window, running the watcher on
  // the data folder the installed dashboard reads.
  const watcherArgs = '--headless powershell.exe -NoProfile -ExecutionPolicy Bypass'
    + ' -File "[INSTALLDIR]resources\\Watch-Device.ps1"'
    + ` -DataFolder "[LocalAppDataFolder]${NAME}\\Data"`;
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by dashboard/scripts/msi.js - edit that, not this. -->
<Wix xmlns="http://schemas.microsoft.com/wix/2006/wi">
  <Product Id="*" Name="${NAME}" Language="1033" Version="${version}" Manufacturer="${MANUFACTURER}" UpgradeCode="${UPGRADE_CODE}">
    <Package InstallerVersion="500" Compressed="yes" InstallScope="perUser" InstallPrivileges="limited" Platform="x64"
             Description="${NAME}" Comments="${NAME} ${version}" />

    <MajorUpgrade Schedule="afterInstallInitialize"
                  DowngradeErrorMessage="A newer version of ${NAME} is already installed." />
    <MediaTemplate EmbedCab="yes" CompressionLevel="high" />

    <Icon Id="app.ico" SourceFile="${xml(icon)}" />
    <Property Id="ARPPRODUCTICON" Value="app.ico" />
    <SetProperty Id="ARPINSTALLLOCATION" Value="[INSTALLDIR]" After="CostFinalize" />

    <!-- Where the last install of this app went, so an update lands on top of it. -->
    <Property Id="INSTALLDIR">
      <RegistrySearch Id="RememberedDir" Root="HKCU" Key="${xml(REG)}" Name="InstallDir" Type="raw" />
    </Property>

    <Directory Id="TARGETDIR" Name="SourceDir">
      <Directory Id="LocalAppDataFolder">
        <Directory Id="INSTALLDIR" Name="${NAME}">
${tree.join('\n')}
          <Component Id="RememberDir" Guid="${guid('<remember>')}">
            <RegistryValue Root="HKCU" Key="${xml(REG)}" Name="InstallDir" Type="string" Value="[INSTALLDIR]" KeyPath="yes" />
          </Component>
        </Directory>
      </Directory>
      <Directory Id="ProgramMenuFolder">
        <Component Id="StartMenuShortcut" Guid="${guid('<start menu>')}">
          <Shortcut Id="StartMenuShortcut" Name="${NAME}" Target="[INSTALLDIR]${EXE}" WorkingDirectory="INSTALLDIR" />
          <RegistryValue Root="HKCU" Key="${xml(REG)}" Name="StartMenuShortcut" Type="integer" Value="1" KeyPath="yes" />
        </Component>
      </Directory>
      <Directory Id="DesktopFolder">
        <Component Id="DesktopShortcut" Guid="${guid('<desktop>')}">
          <Shortcut Id="DesktopShortcut" Name="${NAME}" Target="[INSTALLDIR]${EXE}" WorkingDirectory="INSTALLDIR" />
          <RegistryValue Root="HKCU" Key="${xml(REG)}" Name="DesktopShortcut" Type="integer" Value="1" KeyPath="yes" />
        </Component>
      </Directory>
      <!-- Starts the watcher at login. It stops on its own when no device is watched. -->
      <Directory Id="StartupFolder">
        <Component Id="LoginShortcut" Guid="${guid('<login>')}">
          <Shortcut Id="LoginShortcut" Name="${NAME} watcher" Target="[System64Folder]conhost.exe"
                    Arguments="${xml(watcherArgs)}" WorkingDirectory="INSTALLDIR" Icon="app.ico"
                    Description="Watches your devices in the background" />
          <RegistryValue Root="HKCU" Key="${xml(REG)}" Name="LoginShortcut" Type="integer" Value="1" KeyPath="yes" />
        </Component>
      </Directory>
    </Directory>

    <Feature Id="Complete" Title="${NAME}" Level="1">
${refs.join('\n')}
    </Feature>

    <!-- Welcome, then where to install, then install. No licence page. -->
    <Property Id="WIXUI_INSTALLDIR" Value="INSTALLDIR" />
    <Property Id="WIXUI_EXITDIALOGOPTIONALCHECKBOXTEXT" Value="Open ${NAME}" />
    <Property Id="WIXUI_EXITDIALOGOPTIONALCHECKBOX" Value="1" />
    <Property Id="WixShellExecTarget" Value="[#${exeId}]" />
    <CustomAction Id="OpenApp" BinaryKey="WixCA" DllEntry="WixShellExec" Impersonate="yes" />
    <UI>
      <UIRef Id="WixUI_InstallDir" />
      <Publish Dialog="WelcomeDlg" Control="Next" Event="NewDialog" Value="InstallDirDlg" Order="2">1</Publish>
      <Publish Dialog="InstallDirDlg" Control="Back" Event="NewDialog" Value="WelcomeDlg" Order="2">1</Publish>
      <Publish Dialog="ExitDialog" Control="Finish" Event="DoAction" Value="OpenApp">WIXUI_EXITDIALOGOPTIONALCHECKBOX = 1 and NOT Installed</Publish>
    </UI>
  </Product>
</Wix>
`;
}

/**
 * Builds the installer.
 *
 * @param {{ source: string, version: string, icon: string, out: string, work: string }} o
 *   source - the unpacked app (electron-builder's win-unpacked)
 *   work   - a folder for the generated .wxs and .wixobj
 */
function buildMsi({ source, version, icon, out, work }) {
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`An installer version must be three numbers, not "${version}"`);
  const candle = wixTool('candle');
  const light = wixTool('light');
  const { tree, components, exeId } = harvest(source);
  fs.rmSync(work, { recursive: true, force: true });
  fs.mkdirSync(work, { recursive: true });
  const wxs = path.join(work, 'local-device-monitor.wxs');
  fs.writeFileSync(wxs, product({ version, icon, tree, components, exeId }));
  const ext = ['-ext', 'WixUIExtension', '-ext', 'WixUtilExtension'];
  const obj = path.join(work, 'local-device-monitor.wixobj');
  execFileSync(candle, ['-nologo', '-arch', 'x64', ...ext, '-out', obj, wxs], { stdio: 'inherit' });
  fs.mkdirSync(path.dirname(out), { recursive: true });
  // ICE91: files in a per-user folder "could be per-machine if ALLUSERS=1" - true of any
  // per-user package, and this one is per-user on purpose.
  execFileSync(light, ['-nologo', ...ext, '-cultures:en-us', '-spdb', '-sice:ICE91', '-out', out, obj], { stdio: 'inherit' });
  return { out, files: tree.filter((l) => l.includes('<File ')).length, components: components.length };
}

module.exports = { buildMsi, NAME, EXE };
